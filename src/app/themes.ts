export function themeVars(t: Theme): Record<string, string> {
  return {
    '--bg': t.bg,
    '--surface': t.surface,
    '--surface-alt': t.surfaceAlt,
    '--border': t.border,
    '--primary': t.primary,
    '--accent': t.accent,
    '--highlight': t.highlight,
    '--text': t.text,
    '--text-muted': t.textMuted,
    '--heading-font': t.headingFont,
    '--body-font': t.bodyFont,
    '--shadow': t.dark ? '0 1px 2px rgba(0,0,0,.5), 0 8px 24px rgba(0,0,0,.35)'
                      : '0 1px 2px rgba(16,24,40,.06), 0 8px 24px rgba(16,24,40,.08)',
  };
}
